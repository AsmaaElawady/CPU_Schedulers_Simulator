public class Process {
    String name;
    String color;
    int arrivalTime;
    int burstTime;
    int priorityNumber;

    public Process(String name, String color, int arrivalTime, int burstTime, int priorityNumber){
        this.name = name;
        this.color = color;
        this.arrivalTime = arrivalTime;
        this.burstTime = burstTime;
        this.priorityNumber = priorityNumber;
    }

    
}
